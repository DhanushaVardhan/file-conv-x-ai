// Writes public/js/catalog.js from lib/catalog.js, so the browser can list every
// engine (as locked cards) even when there is no server, e.g. in the artifact preview.
// Run: node tools/build_catalog.mjs          (write)
//      node tools/build_catalog.mjs --check  (exit 1 if out of date)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { lockedCatalog } from '../lib/catalog.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, 'public', 'js', 'catalog.js');

export function catalogSource() {
  return '/* Generated by tools/build_catalog.mjs from lib/catalog.js. Do not edit by hand. */\n' +
    'window.ALEMBIC_CATALOG = ' + JSON.stringify(lockedCatalog(), null, 1) + ';\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = catalogSource();
  if (process.argv.includes('--check')) {
    const same = existsSync(out) && readFileSync(out, 'utf8') === src;
    console.log(same ? 'public/js/catalog.js is up to date' : 'public/js/catalog.js is OUT OF DATE: run node tools/build_catalog.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(out, src);
  console.log('wrote', out, src.length, 'bytes');
}
